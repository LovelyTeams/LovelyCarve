"""Independently encode invented Minix fixtures and unpack util-linux dumps.

The upstream hexdumps were generated by mkfs.minix and checked by fsck.minix.
No Rust reader or writer is used to encode any fixture here.
"""
import hashlib
import json
from pathlib import Path
import re
import struct
import zlib

OUTPUT = Path(__file__).resolve().parent.parent / 'src-tauri/vendor/minix-reader/tests/fixtures'


def unpack_dump(text):
    output = bytearray()
    previous = None
    repeated = False
    for line in text.splitlines():
        if line == '*':
            repeated = True
            continue
        match = re.match(r'^([0-9a-f]{8})($|\s)', line)
        if not match:
            continue
        offset = int(match.group(1), 16)
        if repeated:
            assert previous is not None and (offset - len(output)) % len(previous) == 0
            output.extend(previous * ((offset - len(output)) // len(previous)))
            repeated = False
        assert len(output) == offset
        words = line[match.end():].split('|')[0].split()
        if words:
            previous = bytes(int(word, 16) for word in words)
            assert len(previous) == 16
            output.extend(previous)
    assert len(output) == 16384
    return output


def synthetic(version, names, block_size=1024, shift=0, order='<'):
    zone_size = block_size << shift
    zones = 256
    first = max(8, (4 * block_size + 16 * (32 if version == 1 else 64) + zone_size - 1) // zone_size)
    image = bytearray(zones * zone_size)

    def put(offset, code, *values):
        struct.pack_into(order + code, image, offset, *values)

    if version == 3:
        put(1024, 'IHHHHHHIIHHHB', 16, 0, 1, 1, first, shift, 0,
            0xffffffff, zones, 0x4d5a, 0, block_size, 0)
    else:
        put(1024, 'HHHHHHIHHI', 16, zones if version == 1 else 0, 1, 1,
            first, shift, 0xffffffff, (0x137f if names == 14 else 0x138f) if version == 1
            else (0x2468 if names == 14 else 0x2478), 1, zones if version == 2 else 0)

    def bit(start, index):
        image[start + index // 8] |= 1 << (index % 8)

    for index in range(9):
        bit(2 * block_size, index)
    bit(3 * block_size, 0)

    def allocated(zone):
        bit(3 * block_size, zone - first + 1)
        return zone * zone_size

    def inode(number, mode, size, pointers):
        offset = 4 * block_size + (number - 1) * (32 if version == 1 else 64)
        if version == 1:
            put(offset, 'HHIIBB', mode, 1000, size, 1700000001, 100, 2)
            put(offset + 14, '9H', *(pointers + [0] * (9 - len(pointers))))
        else:
            put(offset, 'HHHHIIII', mode, 2, 1000, 100, size, 1700000000, 1700000001, 1700000002)
            put(offset + 24, '10I', *(pointers + [0] * (10 - len(pointers))))

    def directory(number, zone, parent, children):
        entries = [('.', number), ('..', parent)] + children
        width = 4 if version == 3 else 2
        stride = width + names
        offset = allocated(zone)
        for index, (name, child) in enumerate(entries):
            put(offset + index * stride, 'I' if width == 4 else 'H', child)
            name = name.encode()
            image[offset + index * stride + width:offset + index * stride + width + len(name)] = name
        inode(number, 0x41ed, len(entries) * stride, [zone])

    root_zone, sub_zone = first, first + 1
    file_zone, second_zone, single, double, double_child = range(first + 2, first + 7)
    triple, triple_mid, triple_low, tail = range(first + 7, first + 11)
    link_zone, text_zone = first + 11, first + 12
    width = 2 if version == 1 else 4
    pointers = block_size // width
    code = 'H' if width == 2 else 'I'
    size = (7 + pointers + 2) * zone_size + 37
    inode(2, 0x81a4, size, [file_zone, 0, second_zone, 0, 0, 0, 0, single, double])
    for zone, factor in [(file_zone, 13), (second_zone, 17), (tail, 19)]:
        start = allocated(zone)
        image[start:start + zone_size] = bytes((index * factor + 7) & 255 for index in range(zone_size))
    start = allocated(single)
    put(start, code, second_zone)
    # Non-pointer bytes in the remainder of a multi-block indirect zone are
    # deliberately nonzero. They must not extend the indirect fanout.
    image[start + block_size:start + zone_size] = b'\xff' * (zone_size - block_size)
    put(allocated(double), code, double_child)
    put(allocated(double_child) + 2 * width, code, tail)
    inode(3, 0x81a4, 11, [text_zone])
    start = allocated(text_zone)
    image[start:start + 11] = b'hello minix'
    inode(5, 0xa1ff, 7, [link_zone])
    start = allocated(link_zone)
    image[start:start + 7] = b'big.bin'
    directory(4, sub_zone, 1, [('nested.txt', 3)])
    children = [('big.bin', 2), ('alias.bin', 2), ('deleted', 0),
                ('sub', 4), ('link', 5), ('text.txt', 3)]
    if version != 1:
        # A sparse file reaches triple-indirect storage without allocating or
        # reading the preceding 64 MiB+ logical range.
        triple_start = (7 + pointers + pointers * pointers) * zone_size
        if triple_start + 37 <= 0xffffffff:
            inode(6, 0x81a4, triple_start + 37, [0] * 9 + [triple])
            put(allocated(triple), code, triple_mid)
            put(allocated(triple_mid), code, triple_low)
            put(allocated(triple_low), code, tail)
            children += [('triple.bin', 6)]
    directory(1, root_zone, 1, children)
    return image


if __name__ == '__main__':
    OUTPUT.mkdir(parents=True, exist_ok=True)
    for version, names, block_size, shift, order in [
        (1, 14, 1024, 0, '<'), (1, 30, 1024, 1, '>'),
        (2, 14, 1024, 0, '>'), (2, 30, 1024, 2, '<'),
        (3, 60, 1024, 0, '<'), (3, 60, 2048, 0, '>'),
        (3, 60, 4096, 0, '<'),
    ]:
        payload = synthetic(version, names, block_size, shift, order)
        name = f'v{version}-{names}-{block_size}-{shift}-' + ('le' if order == '<' else 'be')
        (OUTPUT / (name + '.zlib')).write_bytes(zlib.compress(payload, 9))
    for path in sorted((OUTPUT / 'util-linux').glob('fsck-images-v*')):
        payload = unpack_dump(path.read_text(encoding='utf-8'))
        (OUTPUT / (path.name + '.zlib')).write_bytes(zlib.compress(payload, 9))
    records = []
    revision = 'fbfd2ef405d048e8fc01b309b051d2b403b09853'
    for path in sorted(OUTPUT.glob('*.zlib')):
        compressed = path.read_bytes()
        payload = zlib.decompress(compressed)
        upstream = path.name.startswith('fsck-images')
        records.append({'file': path.name, 'sha256': hashlib.sha256(compressed).hexdigest(),
                        'logical_bytes': len(payload), 'logical_sha256': hashlib.sha256(payload).hexdigest(),
                        'source': (f'https://github.com/util-linux/util-linux/blob/{revision}/tests/expected/minix/' + path.stem) if upstream else 'scripts/minix-fixtures.py',
                        'license': 'GPL-2.0-or-later (upstream test data)' if upstream else 'CC0-1.0'})
        if upstream:
            source_text = (OUTPUT / 'util-linux' / path.stem).read_text(encoding='utf-8')
            records[-1]['source_utf8_lf_sha256'] = hashlib.sha256(source_text.encode()).hexdigest()
    (OUTPUT / 'manifest.json').write_text(json.dumps(records, indent=2) + '\n', encoding='utf-8')
